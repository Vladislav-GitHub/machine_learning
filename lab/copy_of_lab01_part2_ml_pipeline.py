from sklearn.base import clone
from tqdm import tqdm

N_vals = [2] + list(range(5, 101, 5))
N_max = max(N_vals)
rng = np.random.default_rng(1)
n_train = len(y_train)
bootstrap_idx = [rng.integers(0, n_train, size=n_train)
                 for _ in range(N_max)]
models = []
tree_models = []

for idx in tqdm(bootstrap_idx):
    model = clone(be)
    model.fit(X_train[idx], y_train[idx])
    models.append(model)

    model_tree = clone(tree)
    model_tree.fit(X_train[idx], y_train[idx])
    tree_models.append(model_tree)

print('Кол-во регрессий:', len(models))
print('Кол-во решающих деревьев:', len(tree_models))

def evaluate_bagging(models, X_test, y_test, N_vals):
    results = []
    probs = [model.predict_proba(X_test) for model in models]

    for n in N_vals:
        mean_proba = np.mean(probs[:n], axis=0)
        y_pred = models[0].classes_[np.argmax(mean_proba, axis=1)]
        results.append({
            'N': n,
            'accuracy': accuracy_score(y_test, y_pred),
            'f1': f1_score(y_test, y_pred, average='macro')
        })

    return pd.DataFrame(results)

